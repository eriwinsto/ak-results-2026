"""Convert an RCTab JSON results file into site/data/rcv/<contest>.json.

Usage:
  python3 scripts/build_rcv.py path/to/..._detailed_report.json gov [--label "..."]
  python3 scripts/build_rcv.py path/to/..._detailed_report.csv  ussen

Takes either RCTab report: the .json or the .csv (both land in the config's outputDirectory).

What this does to RCTab's output:
  * If round 1 eliminates RCTab's "Undeclared Write-ins" pseudo-candidate, that round is
    dropped and the rest renumbered, so round numbers line up with the Division's reports
    (the Division leaves write-ins out of round 1).
  * Transfers to "exhausted" are reported as inactive ballots.
  * With continueUntilTwoCandidatesRemain on, RCTab spends a round declaring the winner
    and then repeats the same tallies to keep eliminating. Those repeated rounds are merged,
    so the rounds shown are the eliminations, as in the Division's reports.
  * RCTab candidate names are matched to the Division's names in results.json
    (exact match, then by surname); unmatched names are printed and kept as-is.
"""
import argparse, csv, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WRITEIN = 'Undeclared Write-ins'

def num(x):
    return float(x) if x not in (None, '') else 0.0

def read_csv_report(path):
    """Turn RCTab's CSV detailed report into the same shape as its JSON report."""
    rows = list(csv.reader(open(path, newline='', encoding='utf-8-sig')))
    get = lambda label: next((r for r in rows if r and r[0] == label), None)
    info = {r[0]: r[1] for r in rows if len(r) >= 2 and r[0]}
    hi = next(i for i, r in enumerate(rows) if r and r[0] == 'Rounds')
    n = (len(rows[hi]) - 1) // 3
    elim_row, elect_row = get('Eliminated'), get('Elected')
    cands = []
    for r in rows[hi + 1:]:
        if not r or r[0] == 'Active Ballots':
            break
        if r[0] not in ('Eliminated', 'Elected'):
            cands.append(r)
    cell = lambda r, i, k: (r[1 + 3 * i + k] if r and len(r) > 1 + 3 * i + k else '').strip()
    split = lambda v: [x.strip() for x in v.split(';') if x.strip()] if v else []
    inact = {k: get(f'Inactive Ballots by {lab}') for k, lab in
             [('overvotes', 'Overvotes'), ('skippedRankings', 'Skipped Rankings'),
              ('exhaustedChoices', 'Exhausted Choices'), ('repeatedRankings', 'Repeated Rankings')]}
    tot_inact, thresh = get('Inactive Ballots Total'), get('Current Round Threshold')
    gone, results = set(), []
    for i in range(n):
        tally = {r[0]: cell(r, i, 0) for r in cands if r[0] not in gone}
        elim, elect = split(cell(elim_row, i, 0)), split(cell(elect_row, i, 0))
        tr = {r[0]: cell(r, i, 2) for r in cands if num(cell(r, i, 2).replace(',', '')) > 0}
        it = num(cell(tot_inact, i, 2).replace(',', ''))
        if it > 0:
            tr['exhausted'] = str(it)
        res = [{'eliminated': e, 'transfers': tr if j == 0 else {}} for j, e in enumerate(elim)]
        res += [{'elected': e, 'transfers': {} if elim else tr} for e in elect]
        results.append({'round': i + 1, 'tally': tally, 'tallyResults': res,
                        'threshold': cell(thresh, i, 0),
                        'inactiveBallots': {k: cell(v, i, 0) for k, v in inact.items()}})
        gone.update(elim)
    return {'config': {'contest': info.get('Contest', ''), 'generatedBy': info.get('Generated By', '')},
            'results': results,
            'summary': {'totalNumBallots': info.get('Total Number of Ballots', '0'),
                        'undervotes': info.get('Number of Undervotes (No Rankings)', '0')}}

def surname(s):
    s = s.split('/')[0]
    return (s.split(',')[0] if ',' in s else s.split()[-1]).strip().lower()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('rctab_json')
    ap.add_argument('contest', help='contest id in results.json, e.g. gov')
    ap.add_argument('--label', default='')
    ap.add_argument('--results', default=os.path.join(ROOT, 'site', 'data', 'results.json'))
    ap.add_argument('--out', default=None)
    a = ap.parse_args()

    rep = read_csv_report(a.rctab_json) if a.rctab_json.lower().endswith('.csv') else json.load(open(a.rctab_json))
    rounds = rep['results']

    names = {}
    if a.results and os.path.isfile(a.results):
        res = json.load(open(a.results))
        c = next((c for c in res['contests'] if c['id'] == a.contest), None)
        if c:
            for x in c['candidates']:
                names[x['raw']] = x['name']
                names.setdefault(surname(x['raw']), x['name'])

    def nm(s):
        if s in names:
            return names[s]
        if surname(s) in names:
            return names[surname(s)]
        return s

    folded = False
    if rounds and any(t.get('eliminated') == WRITEIN for t in rounds[0]['tallyResults']) \
            and len(rounds[0]['tallyResults']) == 1:
        rounds = rounds[1:]
        folded = True

    out_rounds, unmatched = [], set()
    for i, r in enumerate(rounds):
        tally = {nm(k): num(v) for k, v in r['tally'].items() if k != WRITEIN}
        for k in r['tally']:
            if k != WRITEIN and nm(k) == k and names:
                unmatched.add(k)
        inactive = sum(num(v) for v in r.get('inactiveBallots', {}).values())
        elim, elected, transfers = [], [], {}
        for t in r['tallyResults']:
            if t.get('eliminated'):
                elim.append(nm(t['eliminated']))
                src = nm(t['eliminated'])
            elif t.get('elected'):
                elected.append(nm(t['elected']))
                src = nm(t['elected'])
            else:
                continue
            tr = {}
            for k, v in t.get('transfers', {}).items():
                key = 'Inactive' if k in ('exhausted', 'residual surplus') else nm(k)
                tr[key] = tr.get(key, 0) + num(v)
            if tr:
                transfers[src] = tr
        out_rounds.append({'round': i + 1, 'tally': tally, 'inactive': inactive,
                           'threshold': num(r.get('threshold')),
                           'eliminated': elim, 'elected': elected, 'transfers': transfers})

    # merge "winner declared" rounds that RCTab repeats unchanged before the next elimination
    merged = []
    for r in out_rounds:
        if merged and not merged[-1]['eliminated'] and merged[-1]['tally'] == r['tally'] \
                and abs(merged[-1]['inactive'] - r['inactive']) < 0.5:
            r['elected'] = merged[-1]['elected'] + r['elected']
            merged[-1] = r
        else:
            merged.append(r)
    for i, r in enumerate(merged):
        r['round'] = i + 1
    repeats = len(out_rounds) - len(merged)
    out_rounds = merged

    out = {'contest': a.contest, 'label': a.label,
           'rctab': {'contest': rep['config'].get('contest', ''), 'generatedBy': rep['config'].get('generatedBy', '')},
           'writeInRoundFolded': folded, 'repeatedRoundsMerged': repeats, 'rounds': out_rounds,
           'totalBallots': num(str(rep['summary'].get('totalNumBallots')).replace(',', '')),
           'undervotes': num(str(rep['summary'].get('undervotes', 0)).replace(',', ''))}
    dest = a.out or os.path.join(ROOT, 'site', 'data', 'rcv', f'{a.contest}.json')
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    json.dump(out, open(dest, 'w'), indent=1, ensure_ascii=False)
    if unmatched:
        print('WARNING: RCTab names not matched to Division names:', sorted(unmatched), file=sys.stderr)
    last = out_rounds[-1]
    lead = sorted(last['tally'].items(), key=lambda kv: -kv[1])
    print(f'wrote {dest}: {len(out_rounds)} rounds (write-in round folded: {folded}, repeated rounds merged: {repeats}); final: ' +
          ', '.join(f'{k} {v:,.0f}' for k, v in lead))

if __name__ == '__main__':
    main()
